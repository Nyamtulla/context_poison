"""Does the code a paper names actually exist, and does it contain anything?

`next_cell_plan.md` screens cells by "defenses with code", counted from whether
the paper's artifact field names a repository. Running CD2 showed what that
count is worth: the repository it names has been empty since 2024. This checks
every defense in a cell rather than the five we happened to reach.

Three states, decided by evidence and not by what the paper claims:

    has_code   the remote exists and has at least one ref
    empty      the remote exists and has NO refs - a created, never-pushed repo
    missing    the named remote 404s
    no_url     no repository is named anywhere we looked

`git ls-remote` is the primary probe because it is unauthenticated, unlimited,
and answers exactly the question (refs or no refs). The GitHub REST API is
consulted afterwards for size/pushed_at/issue counts, and is allowed to fail:
it rate-limits at 60 requests/hour unauthenticated, and nothing here depends
on it.

Results are cached, so a rate-limited or interrupted run can be resumed
without re-probing what it already settled.
"""
from __future__ import annotations

import json
import pathlib
import re
import sqlite3
import subprocess
import sys
import urllib.error
import urllib.request

REPO = pathlib.Path(__file__).resolve().parent.parent
DB = REPO / "data" / "paper_explorer.db"
OUT = REPO / "data" / "registries" / "artifact_audit.json"

REPO_RE = re.compile(r"https?://(?:www\.)?github\.com/([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+)")
UA = {"User-Agent": "context-sok-artifact-audit"}

# Infrastructure and third-party repos that appear on an arXiv page without
# being the paper's artifact. The first entry is the reason this list exists:
# arXiv's HTML is generated by LaTeXML and links it in the page footer, so a
# naive scrape marked 13 of 45 defenses "has_code" pointing at the renderer.
BLOCKLIST = {
    "brucemiller/latexml", "langchain-ai/langchain", "meta-llama/llama3",
    "meta-llama/llama", "kingoflolz/mesh-transformer-jax", "cveproject/cvelistv5",
    "huggingface/transformers", "openai/openai-python", "pytorch/pytorch",
    "facebookresearch/faiss", "arxiv/arxiv", "github/github",
}

# A link is the paper's own artifact only if it is introduced as one. Without
# this, the scrape returns every repository the paper cites.
# Repositories established by hand or by having been executed in this campaign.
# The scrape cannot find these - some papers put the link in a PDF footnote or
# a "Reproducibility" paragraph the HTML conversion drops - and reporting them
# as "no repository named" would overstate the finding in the direction that
# happens to suit the argument.
VERIFIED = {
    "RobustRAG": "inspire-group/RobustRAG",
    "PH3 (Pruning Head via PatH PatcHing)": "jinzhuoran/MConflict",
    "ACD (Adaptive Contrastive Decoding)": "younanna/ACD",
    "SCR & CR-DPO (Situated Faithfulness)": "kkkevinkkkkk/situated_faithfulness",
}

# Does the paper itself claim an artifact? Separates "no code exists" from
# "we could not find the code the paper says exists".
CLAIMS_RELEASE = re.compile(
    r"(publicly (?:available|released)|code (?:is|are|will be)|released at|"
    r"available at|we release|open.?source|github\.com|^y\b)", re.I)

RELEASE_CUE = re.compile(
    r"(our code|code (?:is |will be )?(?:publicly )?(?:available|released)|"
    r"we (?:release|provide|open.?source)|implementation is available|"
    r"available at|released at|code and data|project page|artifact)",
    re.I)


def norm(owner: str, name: str) -> str:
    name = re.sub(r"\.git$", "", name).rstrip(".,);]")
    return f"{owner}/{name}"


def urls_from_text(text: str) -> list[str]:
    return [norm(o, n) for o, n in REPO_RE.findall(text or "")]


def _keep(slugs: list[str]) -> list[str]:
    out, seen = [], set()
    for s in slugs:
        if s.lower() in BLOCKLIST or s.lower() in seen:
            continue
        seen.add(s.lower())
        out.append(s)
    return out


def repos_in_context(text: str) -> list[str]:
    """Only links a release sentence introduces.

    Scanning the whole page returns every repository the paper cites plus the
    renderer's own footer link. Requiring a release cue within 240 characters
    before the URL is what separates "here is our code" from "we compare
    against X".
    """
    hits = []
    for m in REPO_RE.finditer(text or ""):
        window = text[max(0, m.start() - 240):m.start()]
        if RELEASE_CUE.search(window):
            hits.append(norm(m.group(1), m.group(2)))
    return _keep(hits)


def arxiv_repo(arxiv_id: str) -> tuple[list[str], str]:
    """Abstract first (high precision), then release-cued links in the HTML."""
    try:
        req = urllib.request.Request(f"https://arxiv.org/abs/{arxiv_id}", headers=UA)
        with urllib.request.urlopen(req, timeout=30) as r:
            page = r.read().decode("utf-8", "replace")
        m = re.search(r'blockquote class="abstract.*?</blockquote>', page, re.S)
        if m:
            found = _keep(urls_from_text(m.group(0)))
            if found:
                return found, "arxiv_abstract"
    except Exception:
        pass
    for v in ("v1", "v2"):
        try:
            req = urllib.request.Request(
                f"https://arxiv.org/html/{arxiv_id}{v}", headers=UA)
            with urllib.request.urlopen(req, timeout=40) as r:
                found = repos_in_context(r.read().decode("utf-8", "replace"))
            if found:
                return found, "arxiv_html_cued"
        except Exception:
            continue
    return [], "none"


def probe(slug: str) -> dict:
    """ls-remote decides. No refs on an existing remote means empty."""
    url = f"https://github.com/{slug}.git"
    try:
        p = subprocess.run(["git", "ls-remote", url],
                           capture_output=True, text=True, timeout=60,
                           env={"GIT_TERMINAL_PROMPT": "0", "PATH": "/usr/bin:/bin"})
    except subprocess.TimeoutExpired:
        return {"state": "timeout", "refs": None}
    if p.returncode != 0:
        err = (p.stderr or "").lower()
        if "not found" in err or "repository not found" in err or "403" in err:
            return {"state": "missing", "refs": 0}
        return {"state": "error", "refs": None, "stderr": (p.stderr or "")[:140]}
    refs = len([l for l in p.stdout.splitlines() if l.strip()])
    return {"state": "has_code" if refs else "empty", "refs": refs}


def api(slug: str) -> dict:
    try:
        req = urllib.request.Request(f"https://api.github.com/repos/{slug}", headers=UA)
        with urllib.request.urlopen(req, timeout=30) as r:
            d = json.loads(r.read().decode())
        return {"size_kb": d.get("size"), "pushed_at": (d.get("pushed_at") or "")[:10],
                "open_issues": d.get("open_issues_count"),
                "created_at": (d.get("created_at") or "")[:10]}
    except Exception as e:
        return {"api_error": type(e).__name__}


def main() -> None:
    channel = sys.argv[1] if len(sys.argv) > 1 else "RAG"
    consequence = sys.argv[2] if len(sys.argv) > 2 else "silent-corruption"

    cache = json.loads(OUT.read_text()) if OUT.exists() else {}
    results = cache.get("results", {}) if isinstance(cache, dict) else {}

    con = sqlite3.connect(DB)
    rows = con.execute(
        """select d.name, p.paper_id, p.title, p.arxiv_id, p.artifacts_released,
                  p.citation_count
           from defense d join paper p on p.paper_id = d.paper_id
           where d.channel = ? and d.consequence = ?
           order by p.citation_count desc""", (channel, consequence)).fetchall()

    print(f"{len(rows)} defenses in {channel} x {consequence}\n", flush=True)
    for name, pid, title, arxiv, art, cites in rows:
        if name in results and results[name].get("state") not in (None, "error", "timeout"):
            continue
        slugs = _keep(urls_from_text(art or ""))
        source = "artifacts_released" if slugs else "none"
        if not slugs and name in VERIFIED:
            slugs, source = [VERIFIED[name]], "verified_by_hand"
        if not slugs and arxiv:
            slugs, source = arxiv_repo(arxiv)
        claim_txt = (art or "").strip()
        claims = bool(CLAIMS_RELEASE.search(claim_txt))
        rec = {"paper_id": pid, "title": title, "arxiv_id": arxiv,
               "citations": cites, "claim": claim_txt[:200],
               "claims_release": claims,
               "url_source": source, "candidates": slugs}
        if not slugs:
            # "unresolved" when the paper says code exists and we could not
            # locate it (our limitation, and an extraction gap); "none_named"
            # when the paper makes no release claim either.
            rec["state"] = "unresolved" if claims else "none_named"
        else:
            best = None
            for slug in slugs[:3]:
                pr = probe(slug)
                pr["slug"] = slug
                if best is None or pr["state"] == "has_code":
                    best = pr
                if pr["state"] == "has_code":
                    break
            rec.update(best)
            # A scraped URL is weaker evidence than one the extraction read out
            # of the paper; label it so a reader can discount it.
            rec["confidence"] = ("high" if source == "artifacts_released"
                                 else "medium" if source == "arxiv_abstract"
                                 else "low")
            if best["state"] in ("has_code", "empty"):
                rec.update(api(best["slug"]))
        results[name] = rec
        print(f"  {str(cites or 0):>4}  {rec['state']:<9} {name[:44]:<46} "
              f"{rec.get('slug', '-')}", flush=True)
        OUT.write_text(json.dumps(
            {"generated": "2026-10-12", "channel": channel,
             "consequence": consequence, "results": results}, indent=1))

    print(f"\nwrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
