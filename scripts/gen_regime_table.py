"""The regime framing test, as a table.

Five payload conditions on one item set, crossing who wrote the payload
against what the payload does. The arms differ in provenance and in mechanism
and in nothing else: same false answer, same slots, same dose, same scorer.

Written from data/registries/regime_framing_test.json so the table cannot
drift from the run. Predictions were committed in
regime_framing_prediction.md before any of it executed.

Out: latex/tables/regime_framing.tex
"""
from __future__ import annotations

import json
import pathlib

REPO = pathlib.Path(__file__).resolve().parent.parent
REG = REPO / "data" / "registries" / "regime_framing_test.json"
OUT = REPO / "latex" / "tables" / "regime_framing.tex"

# Stops at the largest corruption size the defense authors evaluate.
DOSES = [0, 1, 2, 3, 5]
ROWS = [
    ("a1_poisonedrag_x5", r"PoisonedRAG, repeated $\times 5$", "adversarial"),
    ("a2_poisonedrag_x1", r"PoisonedRAG, placed once", "adversarial"),
    ("a3_incidental_stale", r"stale document", "incidental"),
    ("a4_incidental_misretrieval", r"misretrieval", "incidental"),
    ("a5_corpus_poisoning", r"corpus poisoning", "adversarial"),
]


def main():
    d = json.loads(REG.read_text())
    by = {}
    for r in d["results"]:
        by.setdefault(r["arm"], {})[r["n_poison"]] = r
    cb = by["closedbook"][0]
    n, mdr = d["n"], d["mdr_pp_at_n"]

    cells = lambda arm, key: " & ".join(
        f"{by[arm][z][key]:.1f}" for z in DOSES)

    L = [r"% GENERATED by scripts/gen_regime_table.py -- do not hand-edit.",
         r"\begin{table*}[t]", r"\centering",
         r"\caption{Does it take an adversary? Five payloads on the same "
         rf"{n} items, dosed as $j$ of the top ten retrieved passages. The "
         r"two PoisonedRAG rows and the stale document assert the "
         r"\emph{same} false answer in the same slots, so the only variable "
         r"between them is whether the sentence was written to be believed. "
         r"Misretrieval is a real, unmodified passage retrieved for another "
         r"question. Left: how often the model gives the planted answer. "
         rf"Right: accuracy on the gold answer. Threshold {mdr:.1f}\pp{{}} at "
         r"this sample size; the undefended model is the only arm, so no "
         r"defense is involved.}",
         r"\label{tab:regime}", r"\footnotesize",
         r"\begin{tabular}{@{}llrrrrrr" + "c" + r"rrrrrr@{}}",
         r"\toprule",
         r"& & \multicolumn{6}{c}{adopts the planted answer (\%)} & "
         r"& \multicolumn{6}{c}{accuracy on the gold answer (\%)} \\",
         r"\cmidrule(lr){3-8}\cmidrule(lr){10-15}",
         r"payload & provenance & " + " & ".join(str(z) for z in DOSES)
         + r" & & " + " & ".join(str(z) for z in DOSES) + r" \\",
         r"\midrule"]

    for arm, label, prov in ROWS:
        L.append(f"{label} & {prov} & {cells(arm, 'attacked')} & & "
                 f"{cells(arm, 'acc')} \\\\")
    L += [r"\midrule",
          r"no retrieval & --- & \multicolumn{6}{c}{"
          rf"{cb['attacked']:.1f}" + r"} & & \multicolumn{6}{c}{"
          rf"{cb['acc']:.1f}" + r"} \\",
          r"\bottomrule", r"\end{tabular}", r"\end{table*}"]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
