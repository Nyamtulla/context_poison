"""Generate the experiment inventory: what we ran, by kind, with counts.

Section 5 lists the campaign and reports no outcomes. It is almost entirely
counts, so the counts are computed here rather than typed, the same way every
other number in the paper is.

A "kind" is a question the run was built to settle, not a rig or a file
naming convention. Two runs that differ only in which model they used are
the same kind; two runs that differ in whether the attack was built against
the defense are not.

Out: latex/tables/experiments.tex
"""
from __future__ import annotations

import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
REG = REPO / "data" / "registries"
OUT = REPO / "latex" / "tables" / "experiments.tex"
sys.path.insert(0, str(REPO / "scripts"))

from pair_tally import retrieval_runs  # noqa: E402

# Payloads that were optimised against the defense they meet, rather than
# built once and pointed at everything.
ADAPTIVE = {"adaptive distractor", "gradient distractor"}


def load(name):
    return json.loads((REG / name).read_text())


def main():
    runs = retrieval_runs()
    transfer = [r for r in runs if r["role"] == "transfer"]
    pairs = {(r["defense"], r["attack"]) for r in transfer}
    payloads = {r["attack"] for r in transfer}

    agent = [r for r in load("technique_transfer_full_banking.json")["results"]
             if not r.get("error")]
    agent_pairs = {(r["technique_name"], r["attack"]) for r in agent}

    n_adaptive = len({(d, a) for d, a in pairs if a in ADAPTIVE})
    n_models = len(list(REG.glob("alignment_sweep_*.json")))
    n_compose = len(list(REG.glob("compose_*.json")))
    n_impl = len({d for d, _ in pairs if d.startswith("RobustRAG")})

    rows = [
        ("a defense meets a failure from the other literature, in the "
         "retrieval cell", len(pairs), "RQ2"),
        ("the same, inside a tool-using agent", len(agent_pairs), "RQ2"),
        ("the same defense against a different shape of planted passage",
         len(payloads), "RQ3"),
        ("the same model with no document, and on a second model",
         n_models, "RQ4"),
        ("two implementations of one defense design", n_impl, "RQ4"),
        ("an attack built against the defense it meets", n_adaptive, "RQ5"),
        ("two defenses stacked", n_compose, "design rule"),
    ]

    L = ["% GENERATED by scripts/gen_experiment_table.py -- do not hand-edit.",
         "\\begin{table}[t]", "\\centering",
         "\\caption{Every kind of run in the campaign, and the question each "
         "one was built to settle. Counts are distinct runs of that kind, not "
         "scored items.}",
         "\\label{tab:experiments}", "\\small",
         "\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}"
         "p{0.62\\columnwidth}rl@{}}", "\\toprule",
         "what the run does & how many & answers \\\\", "\\midrule"]
    for what, n, rq in rows:
        L.append(f"{what} & {n} & {rq} \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT}")
    for what, n, rq in rows:
        print(f"   {n:4d}  {rq:11s} {what}")


if __name__ == "__main__":
    main()
