"""Generate the open-NQ grid table: each fix against the other literature's mechanisms.

The campaign has two retrieval item sets and they are not interchangeable.
CoConflictQA gives one context passage per item, so a dose there is a
fraction of the chunks that passage is cut into. Open Natural Questions
ships a ranked pool, so a dose there is j of the top ten retrieved passages.
Sections 5 and 6 were written on the first and report it fully. This table
is the second, which finished later and reached the paper only as a count of
pairs.

Two numbers per cell, both against that cell's OWN undefended arm on the
same items at the same dose:

  clean   what the defense costs when nothing is planted (dose 0)
  five    what it is worth at five poisoned passages of ten, which is the
          largest corruption size the RobustRAG authors sweep in their own
          run script at top-k ten

A defense whose clean column is negative is paying rent. One whose saturated
column is positive is earning it back under attack. The two are independent,
and the grid separates methods that do both from methods that do neither.

Cells still running are listed as pending rather than left out, so the table
says what the campaign does not yet cover.

Out: latex/tables/grid.tex
"""
from __future__ import annotations

import json
import pathlib

from pair_tally import grid_file

REPO = pathlib.Path(__file__).resolve().parent.parent
REG = REPO / "data" / "registries"
OUT = REPO / "latex" / "tables" / "grid.tex"
# The ladder stops where the literature stops; see gen_paper_numbers.
TOPDOSE = 5

# The undefended arm and the defended arm carry a different name in each
# author's own harness, and we keep the author's name rather than rewriting
# their output. First match wins.
UNDEF = ("undefended", "base_rag", "rag", "base")
DEFEND = ("defended", "ck", "coiecd", "acd", "scr", "parammute", "dyprag")

PRETTY = {"acd": "ACD", "ckplug": "CK-PLUG", "coiecd": "COIECD",
          "dyprag": "DyPRAG", "parammute": "ParamMute", "scr": "SCR",
          "spare": "SpARE", "robustrag-keyword": "RobustRAG-kw",
          "robustrag-decoding": "RobustRAG-dec",
          "reliabilityrag": "ReliabilityRAG", "spotlighting": "Spotlighting",
          "piguard": "PIGuard", "datasentinel": "DataSentinel"}
ATK = {"poisonedrag": "PoisonedRAG", "corpus_poisoning": "corpus pois.",
       "badrag_dos": "refusal", "badrag_sentiment": "tone",
       "distractor_evidence": "third answer", "misretrieval": "misretrieval",
       "incidental_stale": "stale doc.",
       "context_dilution": "dilution"}
# Two panels, one per direction of the campaign. Each fix met the other
# literature's mechanisms, so a single fix-by-mechanism grid was mostly dashes:
# the pairs nobody set out to run. Each panel holds one direction, and the
# rows below its rule are fixes meeting their own literature's mechanisms,
# there for reference.
ATTACKS = ["poisonedrag", "corpus_poisoning", "badrag_dos", "badrag_sentiment"]
HONEST = ["distractor_evidence", "misretrieval", "incidental_stale",
          "context_dilution"]
COLS = ATTACKS + HONEST
SAFETY = ["acd", "ckplug", "coiecd", "dyprag", "parammute", "scr"]
# AttnTrace is absent on purpose: it is reported as tracing only, and its
# defended arm is a removal step its authors do not propose.
SECURITY = ["robustrag-keyword", "robustrag-decoding", "reliabilityrag",
            "spotlighting", "piguard", "datasentinel"]
ROWS = SAFETY + SECURITY
PANELS = [("(a) Fixes for honest mistakes, facing attacks",
           ATTACKS, SAFETY, SECURITY),
          ("(b) Defenses against attackers, facing honest mistakes",
           HONEST, SECURITY, SAFETY)]


def cell(path):
    """(clean delta, saturated delta) for one run, or None if unreadable."""
    try:
        d = json.loads(path.read_text())
    except Exception:
        return None
    rows = [r for r in (d.get("results") or []) if isinstance(r, dict)]
    arms = {r.get("arm") for r in rows} - {None}
    u = next((a for a in UNDEF if a in arms), None)
    v = next((a for a in DEFEND if a in arms), None)
    if not u or not v:
        return None

    def acc(arm, j):
        return next((r.get("acc") for r in rows
                     if r.get("arm") == arm and r.get("n_poison") == j), None)
    out = []
    for j in (0, TOPDOSE):
        a, b = acc(v, j), acc(u, j)
        out.append(None if None in (a, b) else a - b)
    return tuple(out)


def main():
    grid, pending = {}, []
    for dfn in ROWS:
        for atk in COLS:
            p = grid_file(f"native_{dfn}_{atk}")   # 5-shot ACD rerun if present
            if not p.exists():
                continue
            c = cell(p)
            if c is None or c == (None, None):
                pending.append((dfn, atk))
            else:
                grid[(dfn, atk)] = c

    width = len(ATTACKS)
    L = ["% GENERATED by scripts/gen_grid_table.py -- do not hand-edit.",
         "\\begin{table}[t]", "\\centering",
         "\\caption{Each fix against the other literature's causes on "
         "open Natural Questions: (a)~fixes built for honest mistakes, "
         "facing attacks; (b)~defenses built against attackers, facing "
         "honest mistakes. Rows below a rule meet their own literature's "
         "causes, for reference. Cells are percentage points against the "
         "run's undefended arm on the same items, with nothing planted "
         "(\\emph{clean}) and with five of the top ten retrieved passages "
         "planted (\\emph{5/10}). Refusal and tone are BadRAG's two attacks. "
         "ACD runs with the five example questions its control used, and "
         "its code gives the same examples to the undefended model.}",
         "\\label{tab:grid}", "\\footnotesize",
         "\\setlength{\\tabcolsep}{1.5pt}",
         "\\begin{tabular}{@{}l" + "rr" * width + "@{}}", "\\toprule"]

    def row(dfn, cols):
        cells = []
        for a in cols:
            g = grid.get((dfn, a))
            cells += (["--", "--"] if g is None else
                      [f"${v:+.1f}$" if v is not None else "--" for v in g])
        return f"{PRETTY.get(dfn, dfn)} & " + " & ".join(cells) + " \\\\"

    for k, (title, cols, cross, own) in enumerate(PANELS):
        if k:
            L.append("\\midrule")
        L.append(f"\\multicolumn{{{1 + 2 * width}}}{{@{{}}l}}"
                 f"{{\\emph{{{title}}}}} \\\\")
        L.append(" & " + " & ".join(
            f"\\multicolumn{{2}}{{c}}{{{ATK.get(a, a)}}}" for a in cols)
            + " \\\\")
        L.append("".join(f"\\cmidrule(lr){{{2+2*i}-{3+2*i}}}"
                         for i in range(width)))
        L.append("fix & " + " & ".join(["clean & 5/10"] * width) + " \\\\")
        L.append("\\midrule")
        for dfn in cross:
            if any((dfn, a) in grid for a in cols):
                L.append(row(dfn, cols))
        mine = [d for d in own if any((d, a) in grid for a in cols)]
        if mine:
            L.append("\\cmidrule(l){1-%d}" % (1 + 2 * width))
            L += [row(d, cols) for d in mine]
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT}  ({len(grid)} cells, {len(COLS)} causes, "
          f"{len({d for d, _ in grid})} defenses)")
    if pending:
        print("  pending (file present, arms incomplete):")
        for d, a in pending:
            print(f"    {d} x {a}")


if __name__ == "__main__":
    main()
