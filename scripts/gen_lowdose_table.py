"""Generate the 10% dose table from the registries.

The table this replaces was typed by hand and went stale the moment the
gradient run landed: it still said ACD met four payloads when ACD had met
five, so the headline "not one of 15 pairs" undercounted its own evidence.
The project rule is that no count is typed into the prose, and a table of
counts is prose.

A (defense, payload) pair "helps" when the defended arm beats its own
undefended arm, on gold accuracy, by more than that run's detectability
threshold. Anything smaller is not a benefit we can resolve at this sample
size, which is the same rule Section 6 applies everywhere else.

Runs of the same (defense, payload) under different environments collapse to
one pair, with the most recent kept, so the ACD environment re-run does not
count twice.

Out: latex/tables/lowdose.tex
"""
from __future__ import annotations

import collections
import json
import pathlib

REPO = pathlib.Path(__file__).resolve().parent.parent
REG = REPO / "data" / "registries"
OUT = REPO / "latex" / "tables" / "lowdose.tex"
DOSE = 0.1

LABEL = {"corpus_poisoning": "corpus poisoning", "false_evidence": "false evidence",
         "distractor_evidence": "distractor", "adaptive_evidence": "adaptive",
         "gradient_evidence": "gradient"}
NAME = {"acd": "ACD", "ckplug": "CK-PLUG", "coiecd": "COIECD",
        "parammute": "ParamMute", "spare": "SpARE", "scr": "SCR",
        "dyprag": "DyPRAG", "shift": "SHIFT", "faithfulrag": "FaithfulRAG"}


def main():
    # (defense, attack) -> (shortfall, mdr, mtime); later file wins
    best = {}
    for f in sorted(REG.glob("*.json")):
        try:
            d = json.loads(f.read_text())
        except Exception:
            continue
        if not isinstance(d, dict) or not d.get("results"):
            continue
        dfs = (d.get("defense") or f.stem.split("_")[0] or "").lower().replace("-", "")
        if dfs not in NAME:
            continue
        atk = d.get("attack") or ("corpus_poisoning" if "corpus_poisoning" in f.stem
                                  else None)
        if atk not in LABEL:
            continue
        # ctx_acc is required: the BadRAG and PoisonedRAG runs report acc and
        # asr against a count of poisoned passages rather than a fraction of
        # the context, which is a different dosing model and not comparable
        # here.
        arms = {r["arm"]: r for r in d["results"]
                if isinstance(r, dict) and r.get("frac") == DOSE
                and r.get("arm") and "ctx_acc" in r}
        # Every runner names its arms after its own defense, so match on
        # role. SpARE is deliberately excluded by this: its two arms are
        # steer-to-context and steer-to-parameter, with no plain RAG baseline,
        # so there is nothing to measure a benefit against.
        UND = ("rag", "base", "undefended", "naive", "base_rag", "vanilla")
        und = next((v for k, v in arms.items()
                    if k.lower() in UND or k.lower().startswith("base")), None)
        defended = [v for k, v in arms.items()
                    if k.lower() not in UND and not k.lower().startswith("base")
                    and "closed" not in k.lower()]
        if not und or not defended:
            continue
        delta = defended[0]["ctx_acc"] - und["ctx_acc"]
        mdr = d.get("mdr_pp_at_n") or 0.0
        key = (dfs, atk)
        if key not in best or f.stat().st_mtime > best[key][2]:
            best[key] = (delta, mdr, f.stat().st_mtime)

    by = collections.defaultdict(list)
    for (dfs, atk), (delta, mdr, _) in best.items():
        by[dfs].append((atk, delta, mdr))

    rows, total, helps = [], 0, 0
    for dfs in sorted(by, key=lambda k: NAME[k]):
        items = sorted(by[dfs], key=lambda x: x[1])
        h = sum(1 for _, delta, mdr in items if delta > mdr)
        worst_atk, worst_d, _ = items[0]
        total += len(items)
        helps += h
        rows.append(f"{NAME[dfs]:<10}& {len(items)} & {h} & "
                    f"{LABEL[worst_atk]} \;\; ${worst_d:+.1f}$ \\\\")

    L = ["% GENERATED by scripts/gen_lowdose_table.py -- do not hand-edit.",
         r"\begin{table}[t]", r"\centering",
         r"\caption{Every defense against every payload it met, at the 10\% "
         r"dose. ``Helps'' means the defended arm beats its own undefended arm "
         r"by more than that run's detectability threshold. Worst case is the "
         r"payload with the largest shortfall.}",
         r"\label{tab:lowdose}", r"\small",
         r"\begin{tabular}{@{}lrrl@{}}", r"\toprule",
         r"defense & payloads & helps on & worst payload met \\", r"\midrule"]
    L += rows
    L += [r"\midrule",
          f"\\textbf{{total}} & \\textbf{{{total}}} & \\textbf{{{helps}}} & \\\\",
          r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT.relative_to(REPO)}")
    print(f"  {len(rows)} defenses, {total} (defense, payload) pairs, "
          f"{helps} help")
    for dfs in sorted(by, key=lambda k: NAME[k]):
        print(f"    {NAME[dfs]:<12} " +
              ", ".join(f"{LABEL[a]} {d:+.1f}" for a, d, _ in sorted(by[dfs])))
    return total, helps


if __name__ == "__main__":
    main()
