"""Generate the PRISMA flow figure and the search log.

Both are replicability deliverables the project plan asks for and neither
existed. Every count is read from data/context_sok.db and the corpus
export, so no stage number is typed by hand.

One stage cannot be reconstructed. The title/abstract screen left 10,188
records, and 1,158 received full-text extraction. Nothing recorded says how
that subset was chosen. The figure labels that edge as unrecorded rather
than inventing a rule for it, and THREATS.md carries the same statement.

Out: latex/figures/fig9_prisma.pdf, SEARCH_LOG.md
"""
from __future__ import annotations

import pathlib
import sqlite3

import openpyxl

REPO = pathlib.Path(__file__).resolve().parent.parent
DB = REPO / "data" / "context_sok.db"
XLSX = REPO / "data" / "exports" / "paper_dashboard_source.xlsx"


def counts():
    c = sqlite3.connect(DB)
    g = lambda s: list(c.execute(s))
    n = {}
    n["hop0"] = g("select count(*) from papers where hop=0")[0][0]
    n["hop1"] = g("select count(*) from papers where hop=1")[0][0]
    n["hop2"] = g("select count(*) from papers where hop=2")[0][0]
    n["seeds"] = g("select count(*) from papers where discovered_via='seed'")[0][0]
    # restricted to the working pool: the unrestricted totals include the
    # hop-2 fan-out, which is out of scope and would overstate the snowball.
    n["search"] = g("select count(*) from papers where hop<=1 and discovered_via='search'")[0][0]
    n["fwd"] = g("select count(*) from papers where hop<=1 and discovered_via='forward'")[0][0]
    n["bwd"] = g("select count(*) from papers where hop<=1 and discovered_via='backward'")[0][0]
    n["manual"] = g("select count(*) from papers where hop<=1 and discovered_via='manual'")[0][0]
    n["pool"] = n["hop0"] + n["hop1"]
    for k in ("auto_include", "auto_exclude", "needs_review"):
        n[k] = g(f"select count(*) from papers where hop<=1 and screen_auto='{k}'")[0][0]
    n["survived"] = n["auto_include"] + n["needs_review"]
    n["queries"] = g("select count(*) from search_log")[0][0]
    n["apis"] = g("select count(distinct api) from search_log")[0][0]
    n["first_run"] = g("select min(timestamp) from search_log")[0][0][:10]
    n["last_run"] = g("select max(timestamp) from search_log")[0][0][:10]

    sa = dict(c.execute("select paper_id, screen_auto from papers"))
    hp = dict(c.execute("select paper_id, hop from papers"))
    wb = openpyxl.load_workbook(XLSX, read_only=True)
    ws = wb["Papers"]
    rows = list(ws.iter_rows(values_only=True))
    wb.close()
    hdr = list(rows[0])
    pid, scr = hdr.index("paper_id"), hdr.index("screening")
    ids = [r[pid] for r in rows[1:]]
    n["fulltext"] = len(ids)
    n["included"] = sum(1 for r in rows[1:] if str(r[scr]).strip() != "Exclude")
    n["excluded_ft"] = n["fulltext"] - n["included"]
    n["reinstated"] = sum(1 for i in ids if sa.get(i) == "auto_exclude")
    n["from_survivors"] = n["fulltext"] - n["reinstated"]
    n["not_retrieved"] = n["survived"] - n["from_survivors"]
    n["hop2_in"] = sum(1 for i in ids if hp.get(i) == 2)

    # Eligibility for synthesis, added 2026-10-22. A paper can be about
    # context poisoning and still name no attack and no defense: surveys,
    # benchmarks, practitioner guides, applications. Those papers are
    # screened in and reported, but they contribute no row to either
    # registry, so the census, the cube and the coverage matrix are not
    # computed over them. AgentDojo is the clearest case -- it is the
    # environment 56 of our own pairs run in, and it names nothing, so
    # coding it to a regime and a cell was a category error.
    import json as _json
    reg = REPO / "data" / "registries"
    contrib = set()
    for fn in ("rq3_pollution_registry.json", "rq4_defense_registry.json"):
        for e in _json.loads((reg / fn).read_text()):
            if e.get("paper_id"):
                contrib.add(e["paper_id"])
    inc_ids = {r[pid] for r in rows[1:] if str(r[scr]).strip() != "Exclude"}
    n["analysed"] = len(inc_ids & contrib)
    n["no_technique"] = n["included"] - n["analysed"]
    return n


def search_log():
    c = sqlite3.connect(DB)
    rows = list(c.execute(
        "select query_string, track, api, timestamp, hit_count "
        "from search_log order by track, query_string, api"))
    out = ["# Search log",
           "",
           "Generated by `scripts/gen_provenance.py` from the `search_log`",
           "table in `data/context_sok.db`. Every row is one executed query.",
           "`hits` is the count the API reported for the query. It is not the",
           "number retained: the year filter (2023 onward) and the title and",
           "abstract screen both run after this point.",
           "",
           "Track A is adversarial poisoning, track B is incidental",
           "contamination. Raw API responses are cached under",
           "`data/cache/raw_responses/`.",
           "",
           "| track | query | API | date | hits |",
           "|---|---|---|---|---|"]
    for q, t, api, ts, hits in rows:
        out.append(f"| {t} | {q} | {api} | {ts[:10]} | {hits:,} |")
    out += ["",
            "## Known gaps",
            "",
            "Semantic Scholar returned HTTP 429 on some snowball lookups, so",
            "the citation expansion is not exhaustive. The failures are in",
            "`data/pipeline_run.log` and `data/snowball_run.log`.",
            "",
            "Hop depth was set to 1. Hop-2 records were discovered before the",
            "depth was dialled back and remain in the database, outside the",
            "working set.",
            ""]
    (REPO / "SEARCH_LOG.md").write_text("\n".join(out))
    print(f"wrote SEARCH_LOG.md ({len(rows)} queries)")


def figure(n):
    """Corpus construction in four stages.

    Each stage is one box: a bold stage name, then two cells side by side.
    The left cell is what the stage removed or what it was given, the right
    cell is what came out of it and went on to the next stage. Every stage
    has the same shape, so the reader learns the layout once.

    All type is ink. Muted grey reads on a screen and disappears in print,
    and these numbers are the content of the figure, not an aside.
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Rectangle, FancyArrowPatch

    INK, MUTED = "#0b0b0b", "#6b6a66"
    COL = 3.49  # IEEEtran \columnwidth, see gen_paper_figures.py

    plt.rcParams.update({"font.family": "serif", "pdf.fonttype": 42,
                         "savefig.bbox": "tight", "savefig.pad_inches": 0.02})

    stages = [
        ("Seeds and database search",
         f"{n['queries']} queries\nacross {n['apis']} APIs",
         f"{n['seeds']} seeds + {n['search']:,} records\nn = {n['hop0']:,}"),
        ("Snowballed, both directions",
         f"discovery pool {n['pool'] + n['hop2']:,}\n"
         f"hop-2, out of scope {n['hop2']:,}",
         f"working pool, hop 0–1\nn = {n['pool']:,}"),
        ("Screened on title and abstract",
         f"excluded against\nwritten criteria {n['auto_exclude']:,}",
         f"survived\nn = {n['survived']:,}"),
        ("Read in full and coded",
         f"never retrieved {n['not_retrieved']:,}\n"
         f"excluded at full text {n['excluded_ft']:,}",
         f"corpus n = {n['included']:,}\n"
         f"{n['analysed']:,} name a technique"),
    ]

    bh, gap, W, X = 0.545, 0.24, 0.84, 0.015
    pad, mid = 0.022, 0.018          # inset from the outer box, gap between
    cw = (W - 2 * pad - mid) / 2     # width of one inner cell
    head_in, cell_in = 0.17, 0.33    # heading band, inner cell height

    H = len(stages) * bh + (len(stages) - 1) * gap + 0.04
    fig = plt.figure(figsize=(COL, H))
    ax = fig.add_axes([0, 0, 1, 1]); ax.set_xlim(0, 1); ax.set_ylim(0, H)
    ax.axis("off")

    y = H - 0.02
    for i, (head, left, right) in enumerate(stages):
        ax.add_patch(Rectangle((X, y - bh), W, bh, facecolor="none",
                               edgecolor=INK, linewidth=0.7))
        ax.text(X + W / 2, y - head_in / 2 - 0.02, head, ha="center",
                va="center", fontsize=6.5, color=INK, fontweight="bold")
        cy = y - head_in - cell_in
        for k, txt in enumerate((left, right)):
            cx = X + pad + k * (cw + mid)
            ax.add_patch(Rectangle((cx, cy), cw, cell_in, facecolor="none",
                                   edgecolor=MUTED, linewidth=0.45))
            ax.text(cx + cw / 2, cy + cell_in / 2, txt, ha="center",
                    va="center", fontsize=5.7, color=INK, linespacing=1.4)
        if i < len(stages) - 1:
            ax.add_patch(FancyArrowPatch(
                (X + W / 2, y - bh), (X + W / 2, y - bh - gap),
                arrowstyle="-|>", mutation_scale=6, color=INK, lw=0.7))
        y -= bh + gap

    out = REPO / "latex" / "figures" / "fig9_prisma.pdf"
    fig.savefig(out); fig.savefig("/tmp/fig9_prisma.png", dpi=300)
    plt.close(fig)
    print(f"wrote {out.relative_to(REPO)}")


def main():
    n = counts()
    for k, v in n.items():
        print(f"  {k:16s} {v}")
    assert n["survived"] + n["auto_exclude"] == n["pool"], "screen stage does not balance"
    assert (n["search"] + n["seeds"] + n["fwd"] + n["bwd"]
            + n["manual"]) == n["pool"], "identification does not balance"
    assert n["included"] + n["excluded_ft"] == n["fulltext"], "full-text stage does not balance"
    assert n["analysed"] + n["no_technique"] == n["included"], \
        "synthesis-eligibility stage does not balance"
    search_log()
    figure(n)


if __name__ == "__main__":
    main()
