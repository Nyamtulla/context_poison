"""Generate the channel table for the taxonomy section, from the registry.

The taxonomy section used to assert that the corpus holds 233 mechanisms and
then name almost none of them: across the whole paper, 17 techniques were
named and 11 of those were ones we ran ourselves. A reader finished the
section knowing the shape of the space and nothing inside it.

This writes the table that fixes it: per channel, how many named mechanisms
each track contributes, and real examples from each. Nothing here is a
category we invented. The channels are the coding axis the corpus was built
on, and the names are the names the papers gave their own contributions.

**Exemplars are chosen by a rule, not by taste.** Within a (channel, track)
cell we drop the entries whose authors gave no name --- the registry records
those as `UNNAMED:` plus a description, which is honest in a registry and
useless in a table --- and then order by how many defenses the coverage matrix
records as having been evaluated against them, most-tested first. So the table
shows what the field has actually engaged with, and ties break on registry
order, which is stable.

Out: latex/tables/channel_exemplars.tex, \\input by sections/03-literatures.tex.
"""
from __future__ import annotations

import collections
import json
import pathlib

REPO = pathlib.Path(__file__).resolve().parent.parent
REG = REPO / "data" / "registries"
OUT = REPO / "latex" / "tables" / "channel_exemplars.tex"
N_EXEMPLARS = 3
MAXLEN = 30


def load(name):
    d = json.loads((REG / name).read_text())
    if isinstance(d, list):
        return d
    for k in ("entries", "mechanisms", "defenses", "pairs", "matches"):
        if isinstance(d.get(k), list):
            return d[k]
    return []


def tex(s):
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"),
                 ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")):
        s = s.replace(a, b)
    return s


def shorten(s):
    """Drop a parenthetical gloss before truncating, so the name survives."""
    if len(s) > MAXLEN and "(" in s:
        s = s.split("(")[0].strip()
    return s if len(s) <= MAXLEN else s[: MAXLEN - 1].rstrip() + "\\,…"


def main():
    mech = load("rq3_pollution_registry.json")
    cov = load("rq5_coverage_matrix.json")

    tested = collections.Counter()
    for p in cov:
        n = (p.get("matched_mechanism_name") or p.get("mechanism_name")
             or p.get("mechanism"))
        if n:
            tested[n] += 1

    by = collections.defaultdict(list)
    for i, x in enumerate(mech):
        name = (x.get("technique_name") or x.get("name") or "").strip()
        by[(x.get("channel") or "?", x.get("track") or "?")].append((i, name))

    channels = sorted({c for c, _ in by},
                      key=lambda c: -sum(len(by.get((c, t), []))
                                         for t in ("Security", "ML/AI", "Both")))

    def cell(ch, tr):
        rows = by.get((ch, tr), [])
        named = [(i, n) for i, n in rows if n and not n.startswith("UNNAMED")]
        named.sort(key=lambda kv: (-tested.get(kv[1], 0), kv[0]))
        ex = [shorten(tex(n)) for _, n in named[:N_EXEMPLARS]]
        return len(rows), ("; ".join(ex) if ex else "---")

    L = [r"% GENERATED by scripts/gen_taxonomy_tables.py -- do not hand-edit.",
         r"\begin{table*}[t]",
         r"\centering",
         r"\caption{Named mechanisms per channel, by track, with the "
         r"most-tested examples each literature contributes. Counts are named "
         r"mechanisms in the registry; examples exclude entries whose authors "
         r"named nothing, and are ordered by how many defenses have been "
         r"evaluated against them. The channels both communities name are the "
         r"first four rows; the last five are named by the security "
         # APPENDIX-OFF: the second sentence points at sections/A-census and
         # is dropped while that appendix is commented out of main.tex.
         r"literature almost alone.}",
         r"\label{tab:channels}",
         r"\small",
         r"\begin{tabular}{@{}lrrp{0.31\textwidth}p{0.31\textwidth}@{}}",
         r"\toprule",
         r"\textbf{Channel} & \textbf{Sec} & \textbf{ML} & "
         r"\textbf{Security names} & \textbf{Machine learning names} \\",
         r"\midrule"]
    for ch in channels:
        ns, es = cell(ch, "Security")
        nm, em = cell(ch, "ML/AI")
        L.append(f"\\meth{{{tex(ch)}}} & {ns} & {nm} & {es} & {em} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT.relative_to(REPO)}  ({len(channels)} channels)")
    for ch in channels:
        ns, _ = cell(ch, "Security")
        nm, _ = cell(ch, "ML/AI")
        print(f"  {ch:<16} Sec {ns:>3}   ML {nm:>3}")


if __name__ == "__main__":
    main()
