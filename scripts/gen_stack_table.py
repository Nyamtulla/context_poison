"""Generate the RQ5 stack table from the stack registries.

One safety fix (ACD, with the five shots its control ran) and two security
filters (DataSentinel, PIGuard), each alone and with the filter in front of
the fix, on three attacks and three honest mistakes. Every arm answers the
same items with the same contexts (scripts/stack_run.py).

Each case gets two rows: the share answered correctly, and the share that did
what the bad passages push for. For PoisonedRAG, corpus poisoning and the
honest mistakes that is the planted answer; BadRAG's refusal attack plants no
answer, so its harm row is the refusal rate.

The 3-item smoke file (`_n3`) is not a result and is left out.

Out: latex/tables/stack.tex
"""
from __future__ import annotations

import json
import pathlib

REPO = pathlib.Path(__file__).resolve().parent.parent
REG = REPO / "data" / "registries"
OUT = REPO / "latex" / "tables" / "stack.tex"

DOSE = 5
# mechanism file stem -> (label, harm metric, harm label, is attack)
CASES = [
    ("p1_poisonedrag_distinct", "PoisonedRAG", "asr", "planted", True),
    ("p1_corpus_poisoning", "corpus pois.", "asr", "planted", True),
    ("p1_badrag_dos", "refusal", "refusal_rate", "refused", True),
    ("distractor_evidence", "third answer", "asr", "planted", False),
    ("misretrieval", "misretrieval", "asr", "planted", False),
    ("incidental_stale", "stale doc.", "asr", "planted", False),
]
ARMS = [("undefended", "none"), ("filter:datasentinel", "DS"),
        ("filter:piguard", "PIG"), ("fix", "ACD"),
        ("stack:datasentinel", "ACD+DS"), ("stack:piguard", "ACD+PIG")]
FILTERS = ("datasentinel", "piguard")


def load(stem):
    doc = json.loads((REG / f"stack_acd_{stem}.json").read_text())
    return doc, {(r["arm"], r["n_poison"]): r for r in doc["results"]}


def stack_vs_best():
    """Stacked accuracy minus the better of its two halves, every case, dose
    and filter. The paper quotes the extremes of this list."""
    out = []
    for stem, *_ in CASES:
        doc, R = load(stem)
        for j in doc["doses"]:
            for f in FILTERS:
                best = max(R[(f"filter:{f}", j)]["acc"], R[("fix", j)]["acc"])
                out.append(R[(f"stack:{f}", j)]["acc"] - best)
    return out


def main():
    lines = [
        "% GENERATED by scripts/gen_stack_table.py -- do not hand-edit.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{A security filter in front of a safety fix, on open Natural "
        "Questions with five of the top ten retrieved passages bad. Each case "
        "has two rows: the percentage answered correctly, and the percentage "
        "that gave the planted answer (for BadRAG's refusal attack, that "
        "refused). \\emph{none}: no defense; DS: the security filter "
        "DataSentinel; PIG: the security filter PIGuard; ACD: the safety fix "
        "ACD, with the five examples its control used. Every column answers "
        "the same items with the same passages; items per case: "
        + ", ".join(f"{lbl} {load(s)[0]['n']}" for s, lbl, *_ in CASES)
        + ".}",
        "\\label{tab:stack}",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{2.5pt}",
        "\\begin{tabular}{@{}ll" + "r" * len(ARMS) + "@{}}",
        "\\toprule",
        " & & " + " & ".join(h for _, h in ARMS) + " \\\\",
        "\\midrule",
        f"\\multicolumn{{{2 + len(ARMS)}}}{{@{{}}l}}{{\\emph{{Attacks}}}} \\\\",
    ]
    honest_started = False
    for stem, label, harm, hlabel, attack in CASES:
        if not attack and not honest_started:
            lines += ["\\midrule",
                      f"\\multicolumn{{{2 + len(ARMS)}}}{{@{{}}l}}"
                      "{\\emph{Honest mistakes}} \\\\"]
            honest_started = True
        _, R = load(stem)
        for i, (key, rl) in enumerate((("acc", "correct"), (harm, hlabel))):
            cells = [f"{R[(a, DOSE)][key]:.1f}" for a, _ in ARMS]
            lines.append(f"{label if i == 0 else ''} & {rl} & "
                         + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
