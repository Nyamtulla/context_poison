"""Generate RUNS.md: every result registry, and the script that produced it.

The producer is not guessed. Each runner names its own output file as a
default, so we grep `scripts/` for each registry's basename and report the
script that mentions it. A registry no script claims is listed as such rather
than being attributed to a plausible neighbour, because an artifact index that
quietly guesses is worse than one that admits a gap.

The command line is reconstructed from the metadata the registry itself
stores (model, dataset, n, attack, doses), so it is a faithful description of
the run's configuration, not a transcript. Runs made before a flag existed are
marked. Where the registry records nothing we say nothing.

Out: RUNS.md
"""
from __future__ import annotations

import json
import pathlib
import re
import subprocess

REPO = pathlib.Path(__file__).resolve().parent.parent
REG = REPO / "data" / "registries"


# Registry name -> the script that writes it. Hand-written, and checked two
# ways by the generator: the script must exist, and a registry that matches no
# rule is listed as unclaimed rather than attributed to a plausible neighbour.
#
# A table is needed because the runners build their own output names, e.g.
# `poisonedrag_transfer.py` defaults to `{attack}_{defense}.json`, so grepping
# the sources for a registry's literal filename finds nothing for 75 of 87.
PRODUCER = [
 (r"^acd_vs_", "scripts/acd_vs_corpus_poisoning.py"),
 (r"^(ckplug_vs_|ck_alpha_|ckplug_control)", "scripts/ckplug_vs_corpus_poisoning.py"),
 (r"^(coiecd_vs_|variance_replicates_coiecd)", "scripts/coiecd_vs_corpus_poisoning.py"),
 (r"^(parammute_vs_|parammute_control)", "scripts/parammute_vs_corpus_poisoning.py"),
 (r"^dyprag_vs_", "scripts/dyprag_vs_corpus_poisoning.py"),
 (r"^scr_vs_", "scripts/scr_vs_corpus_poisoning.py"),
 (r"^spare_vs_", "scripts/spare_vs_corpus_poisoning.py"),
 (r"^(faithfulrag_|frag_control)", "scripts/faithfulrag_vs_corpus_poisoning.py"),
 (r"^shift_", "scripts/shift_vs_corpus_poisoning.py"),
 (r"^corpus_poisoning_vs_robustrag", "scripts/corpus_poisoning_vs_robustrag.py"),
 (r"^alignment_sweep", "scripts/alignment_sweep.py"),
 (r"^instruction_following", "scripts/instruction_following_probe.py"),
 (r"^robustrag_backfill", "scripts/robustrag_backfill.py"),
 # these three build their own names from --attack and --defense
 (r"^(poisonedrag|badrag_\w+)_robustrag", "scripts/robustrag_matrix.py"),
 (r"^(poisonedrag|badrag_\w+)_spare", "scripts/spare_badrag_transfer.py"),
 (r"^(poisonedrag|badrag_\w+)_(ckplug|parammute)", "scripts/poisonedrag_transfer.py"),
 (r"^(technique_transfer|full_attack_screen|v2_attack_screen)",
  "agentdojo_harness/run_technique_transfer.py"),
 (r"^mechanism_triage", "agentdojo_harness/run_mechanism_transfer.py"),
 (r"^control_calibration", "agentdojo_harness/calibrate_control.py"),
]


def producer(name):
    for pat, script in PRODUCER:
        if re.match(pat, name):
            return script if (REPO / script).exists() else ""
    return ""


def command(script, d):
    """Rebuild the invocation from what the registry recorded."""
    if not script:
        return ""
    a = [f"python3 {script}"]
    for flag, key in (("--model", "model"), ("--data", "dataset"),
                      ("--n", "n"), ("--n_shots", "n_shots"),
                      ("--attack", "attack")):
        v = d.get(key)
        if v not in (None, "", "?"):
            a.append(f"{flag} {v}")
    fr = d.get("fracs_done") or sorted(
        {r.get("frac") for r in d.get("results", [])
         if isinstance(r, dict) and r.get("frac") is not None})
    if fr:
        a.append("--fracs " + " ".join(str(x) for x in fr))
    return " ".join(a)


def main():
    rows, orphans = [], []
    for p in sorted(REG.glob("*.json")):
        try:
            d = json.loads(p.read_text())
        except Exception:
            continue
        if not isinstance(d, dict) or not d.get("results"):
            continue
        script = producer(p.name)
        if not script:
            orphans.append(p.name)
        rows.append({
            "file": p.name, "defense": d.get("defense") or "",
            "attack": d.get("attack") or "", "model": d.get("model") or "",
            "n": d.get("n") or "", "script": script,
            "cmd": command(script, d),
            "payload_fp": d.get("payload_fingerprint") or ""})

    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                          cwd=REPO, capture_output=True, text=True).stdout.strip()
    L = [
      "# Run index",
      "",
      f"Generated by `scripts/gen_run_index.py` at `{head}`. "
      f"{len(rows)} result registries.",
      "",
      "Every row is a file under `data/registries/` that holds scored results. "
      "The **script** column comes from the `PRODUCER` table in the "
      "generator, because the runners build their own output names from "
      "`--attack` and `--defense` and so do not contain the filename to grep "
      "for. A registry no rule matches is listed as unclaimed below rather "
      "than attributed to a plausible neighbour. The **command** "
      "is rebuilt from the metadata the registry stores about itself: model, "
      "item set, item count, attack and doses. It is a faithful statement of "
      "the configuration, not a shell transcript.",
      "",
      "`EXPERIMENTS.md` has the setup these commands assume.",
      "",
      "| registry | defense | attack | n | script |",
      "|---|---|---|---:|---|",
    ]
    for r in rows:
        s = f"`{r['script']}`" if r["script"] else "**unclaimed**"
        L.append(f"| `{r['file']}` | {r['defense'] or '—'} | "
                 f"{r['attack'] or '—'} | {r['n'] or '—'} | {s} |")
    L += ["", "## Commands", ""]
    for r in rows:
        if not r["cmd"]:
            continue
        L.append(f"**`{r['file']}`**")
        L.append("")
        L.append("```bash")
        L.append(r["cmd"])
        L.append("```")
        if r["payload_fp"]:
            L.append(f"Payload fingerprint recorded by the run: "
                     f"`{r['payload_fp']}`.")
        L.append("")
    if orphans:
        L += ["## Registries no single script claims", "",
              "These are real results with an unclear producer in the current "
              "tree, usually because the run was driven from a harness "
              "directory or the output path was passed on the command line. "
              "Listed rather than attributed by guess.", ""]
        for n in orphans:
            L.append(f"- `{n}`")
        L.append("")
    (REPO / "RUNS.md").write_text("\n".join(L) + "\n")
    print(f"wrote RUNS.md: {len(rows)} registries, "
          f"{len(rows)-len(orphans)} with a unique producer, "
          f"{len(orphans)} without")


if __name__ == "__main__":
    main()
