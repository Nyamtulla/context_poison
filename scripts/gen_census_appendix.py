"""Generate the full census appendix: every named mechanism and every defense.

The body of the paper describes the biggest families and counts the rest. That
is the right shape for a body, and it leaves a claim unbacked: that we read the
whole corpus rather than the convenient parts of it. This emits the evidence
for that claim as two tables, one row per registry entry, nothing omitted.

**Entries whose authors named nothing are included, in italics.** The body
tables exclude them because an unnamed row is useless as an example. A census
is the opposite case: dropping them here would undercount the corpus and
overstate how much of the field has named its own contributions, which is
itself one of our findings.

**Sources are first author and year, not \\cite.** Citing 783 rows would need
roughly seven hundred bibliography entries and the reference list would become
the paper. Each row's full record, with DOI or arXiv identifier, is in the
released registry JSON, and the appendix says so.

Sorted by channel, then track, then name, so the tables answer the question a
reader actually brings: what is known about this channel, from each side.

Out: latex/tables/census_mechanisms.tex, latex/tables/census_defenses.tex
"""
from __future__ import annotations

import json
import pathlib
import re

import openpyxl

REPO = pathlib.Path(__file__).resolve().parent.parent
R = REPO / "data" / "registries"
OUT = REPO / "latex" / "tables"

CHANNEL_ORDER = ["direct-input", "tool-output", "RAG", "memory", "cross-modal",
                 "tool-metadata", "multi-agent", "supply-chain", "skill"]


def load(n):
    d = json.loads((R / n).read_text())
    if isinstance(d, list):
        return d
    for k in ("entries", "mechanisms", "defenses"):
        if isinstance(d.get(k), list):
            return d[k]
    return []


def regime_label(track):
    """The registry still stores Security / ML-AI; the paper says regimes.

    Renaming the stored value would touch every registry and every script
    that reads one, so the translation lives at the point of printing. If the
    registries are ever re-keyed, delete this and the call sites.
    """
    return {"Security": "security", "ML/AI": "safety",
            "Both": "both"}.get((track or "").strip(), track or "")


def tex(s):
    s = str(s or "")
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"),
                 ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")):
        s = s.replace(a, b)
    return s


def sources():
    """paper_id -> bibkey, from the index build_bibtex.py writes.

    Falls back to first author and year only when a paper has no key, which
    currently never happens: all 715 census sources resolve. The fallback
    stays so that a corpus change surfaces as a visible string in the table
    rather than as a silently dropped citation.
    """
    idx = json.loads((REPO / "manuscript" / "bibkey_index.json").read_text())
    bykey = {v["paper_id"]: k for k, v in idx.items()}
    wb = openpyxl.load_workbook(
        REPO / "data" / "exports" / "paper_dashboard_source.xlsx", read_only=True)  # noqa
    ws = wb["Papers"]
    rows = list(ws.iter_rows(values_only=True))
    wb.close()
    hdr = {h: i for i, h in enumerate(rows[0]) if h}
    out = {}
    for r in rows[1:]:
        pid = r[hdr["paper_id"]]
        if not pid:
            continue
        auth = str(r[hdr.get("authors", -1)] or "").strip()
        year = str(r[hdr.get("year", -1)] or "").strip()
        first = re.split(r"[;,]", auth)[0].strip() if auth else ""
        surname = first.split()[-1] if first else ""
        year = year.split(".")[0]
        if pid in bykey:
            out[pid] = "\\cite{" + bykey[pid] + "}"
        else:
            out[pid] = f"{surname} {year}".strip() if surname else "---"
    n_cited = sum(1 for v in out.values() if v.startswith("\\cite"))
    print(f"  {n_cited}/{len(out)} source papers resolve to a bibkey")
    return out


def name_of(e, key):
    n = (e.get(key) or e.get("name") or "").strip()
    if n.upper().startswith("UNNAMED"):
        body = n.split(":", 1)[1].strip() if ":" in n else n
        return r"\emph{" + tex(body) + "}", True
    return tex(n), False


def emit(path, rows, headers, widths, caption, label, note):
    L = [r"% GENERATED by scripts/gen_census_appendix.py -- do not hand-edit.",
         r"\begingroup", r"\footnotesize",
         r"\setlength{\tabcolsep}{3.5pt}",
         r"\begin{longtable}{@{}" + widths + r"@{}}",
         r"\caption{" + caption + r"}\\",   # raw: longtable needs \\ here r"\label{" + label + r"}\\",
         r"\toprule",
         " & ".join(r"\textbf{" + h + "}" for h in headers) + r" \\",
         r"\midrule", r"\endfirsthead",
         r"\multicolumn{" + str(len(headers)) + r"}{l}{\emph{"
         + note + r"}} \\", r"\toprule",
         " & ".join(r"\textbf{" + h + "}" for h in headers) + r" \\",
         r"\midrule", r"\endhead",
         r"\midrule",
         r"\multicolumn{" + str(len(headers)) + r"}{r}{\emph{continued}} \\",
         r"\endfoot", r"\bottomrule", r"\endlastfoot"]
    L += [" & ".join(r) + r" \\" for r in rows]
    L += [r"\end{longtable}", r"\endgroup", ""]
    path.write_text("\n".join(L))


def main():
    src = sources()
    mech, defs = load("rq3_pollution_registry.json"), load("rq4_defense_registry.json")
    order = {c: i for i, c in enumerate(CHANNEL_ORDER)}
    key = lambda e, k: (order.get(e.get("channel"), 99),
                        e.get("track") or "", (e.get(k) or "").lower())

    mrows, m_unnamed = [], 0
    for e in sorted(mech, key=lambda e: key(e, "technique_name")):
        n, un = name_of(e, "technique_name")
        m_unnamed += un
        mrows.append([n, tex(e.get("channel")), tex(e.get("consequence")),
                      tex(regime_label(e.get("track"))), src.get(e.get("paper_id"), "---")])

    drows, d_unnamed = [], 0
    for e in sorted(defs, key=lambda e: key(e, "defense_name")):
        n, un = name_of(e, "defense_name")
        d_unnamed += un
        drows.append([n, tex(e.get("channel")),
                      tex(e.get("defense_intervention_point")),
                      tex(regime_label(e.get("track"))), tex(e.get("validated_against")),
                      src.get(e.get("paper_id"), "---")])

    OUT.mkdir(parents=True, exist_ok=True)
    emit(OUT / "census_mechanisms.tex", mrows,
         ["Mechanism or attack", "Channel", "Consequence", "Track", "Source"],
         r"p{0.33\textwidth}llll",
         f"Every named mechanism in the corpus ({len(mrows)} entries). Rows in "
         r"\emph{italics} are entries whose authors gave their contribution no "
         "name; they are counted here because excluding them would overstate "
         "how much of the field names what it finds. Every row cites the paper "
         "that named the mechanism; full records with DOI or arXiv identifiers "
         "ship with the artifact.",
         "tab:census-mech",
         f"Table~\\ref{{tab:census-mech}}: named mechanisms, continued")
    emit(OUT / "census_defenses.tex", drows,
         ["Defense or fix", "Channel", "Acts at", "Track", "Validated vs",
          "Source"],
         r"p{0.30\textwidth}lllll",
         f"Every named defense in the corpus ({len(drows)} entries). "
         r"\emph{Validated vs} is the threat model the paper's own evaluation "
         "tested, not the one it claims. Conventions otherwise as in "
         r"Table~\ref{tab:census-mech}.",
         "tab:census-def",
         f"Table~\\ref{{tab:census-def}}: named defenses, continued")

    print(f"  census_mechanisms.tex  {len(mrows):>4} rows "
          f"({m_unnamed} unnamed, {100*m_unnamed/len(mrows):.0f}%)")
    print(f"  census_defenses.tex    {len(drows):>4} rows "
          f"({d_unnamed} unnamed, {100*d_unnamed/len(drows):.0f}%)")
    miss = sum(1 for e in mech + defs if e.get("paper_id") not in src)
    print(f"  {miss} of {len(mech)+len(defs)} rows have no source record")


if __name__ == "__main__":
    main()
